use jet_push_macros::generate_push_macros;

// Mock Instruction enum for testing
#[allow(non_camel_case_types)]
enum Instruction {
    PUSH0,
    PUSH1,
    PUSH2,
    PUSH3,
    PUSH4,
    PUSH5,
    PUSH32,
}

impl Instruction {
    fn opcode(&self) -> u8 {
        match self {
            Instruction::PUSH0 => 0x5F,
            Instruction::PUSH1 => 0x60,
            Instruction::PUSH2 => 0x61,
            Instruction::PUSH3 => 0x62,
            Instruction::PUSH4 => 0x63,
            Instruction::PUSH5 => 0x64,
            Instruction::PUSH32 => 0x7F,
        }
    }
}

// Generate the macros for testing
generate_push_macros!(0..=5);
generate_push_macros!(32..=32);

#[test]
fn test_push0() {
    let result = PUSH0!();
    assert_eq!(result, vec![0x5F]);
}

#[test]
fn test_push1() {
    let result = PUSH1!(0x42);
    assert_eq!(result, vec![0x60, 0x42]);
}

#[test]
fn test_push2() {
    let result = PUSH2!(0x12, 0x34);
    assert_eq!(result, vec![0x61, 0x12, 0x34]);
}

#[test]
fn test_push3() {
    let result = PUSH3!(0xAA, 0xBB, 0xCC);
    assert_eq!(result, vec![0x62, 0xAA, 0xBB, 0xCC]);
}

#[test]
fn test_push4() {
    let result = PUSH4!(0x01, 0x02, 0x03, 0x04);
    assert_eq!(result, vec![0x63, 0x01, 0x02, 0x03, 0x04]);
}

#[test]
fn test_push5() {
    let result = PUSH5!(0xFF, 0xEE, 0xDD, 0xCC, 0xBB);
    assert_eq!(result, vec![0x64, 0xFF, 0xEE, 0xDD, 0xCC, 0xBB]);
}

#[test]
fn test_push32() {
    let result = PUSH32!(
        0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
        0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10,
        0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18,
        0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F, 0x20
    );
    assert_eq!(
        result,
        vec![
            0x7F, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08,
            0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10,
            0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18,
            0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F, 0x20
        ]
    );
}
